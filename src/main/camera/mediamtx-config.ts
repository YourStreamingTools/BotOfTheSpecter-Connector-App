import { CAMERA_API_PORT, CAMERA_SRT_PORT, CAMERA_WEBRTC_PORT, CAMERA_WEBRTC_UDP_PORT } from '@shared/cameras';

export interface MediamtxConfigOptions {
  rtmpPort: number;
  /** Connector web server port; MediaMTX POSTs every publish/read to /internal/mediamtx/auth on it. */
  webPort: number;
  /** When false WebRTC binds to loopback only, so only OBS on this PC can play cameras. */
  lanView: boolean;
  webrtcPort?: number;
  webrtcUdpPort?: number;
  apiPort?: number;
  srtPort?: number;
}

/**
 * MediaMTX v1.21 config for the local camera route. Only RTMP + SRT ingest, WebRTC playback and the
 * loopback API are on; RTSP/HLS/MoQ/recording stay off. Auth is delegated to the Connector.
 */
export function buildMediamtxConfig(o: MediamtxConfigOptions): string {
  const webrtcPort = o.webrtcPort ?? CAMERA_WEBRTC_PORT;
  const udpPort = o.webrtcUdpPort ?? CAMERA_WEBRTC_UDP_PORT;
  const apiPort = o.apiPort ?? CAMERA_API_PORT;
  const srtPort = o.srtPort ?? CAMERA_SRT_PORT;
  const bind = o.lanView ? '' : '127.0.0.1';
  const lines = [
    '# Generated by BotOfTheSpecter Desktop on every start; edits are overwritten.',
    'logLevel: info',
    'logDestinations: [stdout]',
    'readTimeout: 10s',
    'writeTimeout: 10s',
    '',
    'authMethod: http',
    `authHTTPAddress: http://127.0.0.1:${o.webPort}/internal/mediamtx/auth`,
    'authHTTPExclude:',
    '  - action: api',
    '',
    'api: true',
    `apiAddress: 127.0.0.1:${apiPort}`,
    'metrics: false',
    'pprof: false',
    'playback: false',
    '',
    'rtsp: false',
    'hls: false',
    'srt: true',
    `srtAddress: :${srtPort}`,
    'moq: false',
    '',
    'rtmp: true',
    'rtmpEncryption: "no"',
    `rtmpAddress: :${o.rtmpPort}`,
    '',
    'webrtc: true',
    `webrtcAddress: ${bind}:${webrtcPort}`,
    'webrtcEncryption: false',
    'webrtcAllowOrigins: ["*"]',
    `webrtcLocalUDPAddress: ${bind}:${udpPort}`,
    'webrtcLocalTCPAddress: ""',
    `webrtcIPsFromInterfaces: ${o.lanView ? 'true' : 'false'}`,
    `webrtcAdditionalHosts: [${o.lanView ? '' : '127.0.0.1'}]`,
    'webrtcICEServers2: []',
    '',
    'pathDefaults:',
    '  source: publisher',
    '  record: false',
    // A reconnecting phone must replace its own stale session; other phones are refused by the auth hook.
    '  overridePublisher: true',
    '',
    'paths:',
    '  "~^camera/[a-z0-9_-]{1,32}$":',
    ''
  ];
  return lines.join('\n');
}
